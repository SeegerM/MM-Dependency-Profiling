"""What discovery finds on the three published multi-source instances.

MovieLens + TMDB + Wikidata, Helsinki UDBMS Patent and ListenBrainz. For each, selected expected
correspondences are printed beside the degree measured on the loaded instance.

usage: published_instances.py [--work=$WORK_ROOT]
                              [--out=paper/tables/published-instances.txt]
"""
import csv
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "lib"))
import paths  # noqa: E402

HERE = Path(__file__).resolve().parents[2]
TRAILING_COMMA = re.compile(r",\s*([}\]])")
csv.field_size_limit(1 << 24)

# Each entry is (instance, result subdirectory, [(dependent, referenced, what it is)]).
# Expectations come from the source documentation or the data; they are printed, not asserted.
INSTANCES = [
    ("MovieLens + TMDB + Wikidata", "movielens", "meta-results-0.5", [
        ("movielens.links.tmdbid", "tmdb.movies.id",
         "relational to document: MovieLens references TMDB identifiers TMDB has since dropped"),
        ("neo4j:WikidataFilm.wikidata_tmdb_id", "movielens.links.tmdbid",
         "graph to relational: the two publishers disagree on some TMDB identifiers"),
        ("neo4j:WikidataFilm@movielens_movie_ids.movielens_movie_ids", "movielens.movies.movieid",
         "graph list to relational: every Wikidata-mapped film is a MovieLens film"),
        ("movielens.movies.movieid", "neo4j:WikidataFilm@movielens_movie_ids.movielens_movie_ids",
         "relational to graph list: the share of MovieLens films Wikidata maps"),
        ("movielens.links.imdbid", "neo4j:WikidataFilm.imdb_id",
         "relational to graph: the same IMDb identifier, spelled two ways"),
    ]),
    ("Helsinki UDBMS Patent", "hpatent", "meta-results-0.5", [
        ("neo4j:-[CITES]->.source.id", "hpatent.patent.patent",
         "graph edge source to relational: a citing patent is in the corpus"),
        ("neo4j:-[CITES]->.target.id", "hpatent.patent.patent",
         "graph edge target to relational: a cited patent may predate the corpus"),
        ("neo4j:HPatent.id", "hpatent.patent.patent",
         "graph node to relational: identifiers the edge list mentions"),
        ("hpatent.inventor.patent", "hpatent.patent.patent",
         "relational: the publisher's own join between two tables"),
    ]),
    ("ListenBrainz", "listenbrainz", "meta-results-0.5", [
        ("listenbrainz.top_recording.artist_mbid", "neo4j:LBArtist.artist_mbid",
         "relational to graph: every popular artist is in the artist cache"),
        ("neo4j:LBArtist.artist_mbid", "listenbrainz.top_recording.artist_mbid",
         "graph to relational: the cache also holds artists with no popularity row"),
        ("listenbrainz.mlhd_top_recording.artist_mbid", "neo4j:LBArtist.artist_mbid",
         "relational to graph: the same, from the second popularity table"),
    ]),
]


def flag(name, default):
    return next((a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--" + name + "=")),
                default)


def inclusions(results):
    path = results / "1-ary_pINDs.json"
    found = {}
    text = TRAILING_COMMA.sub(r"\1", path.read_text(encoding="utf-8"))
    for relation in json.loads(text):
        for pind in relation.get("pINDs", []):
            dependent = relation["relation"] + "." + ".".join(pind["dependant"])
            for ref in pind["referenced"]:
                found[(dependent, ref["relation"] + "." + ".".join(ref["attribute"]))] = \
                    ref["partialDegree"]
    return found


def catalog_summary(export):
    catalog = json.loads((export / "catalog.json").read_text(encoding="utf-8"))
    return (len(catalog), sum(e["columns"] for e in catalog), sum(e["rows"] for e in catalog))


def main():
    work = Path(flag("work", str(paths.WORK_ROOT)))
    out = Path(flag("out", str(HERE / "paper" / "tables" / "published-instances.txt")))

    lines = [
        "# Published multi-source instances: what discovery reports on layouts we did not choose.",
        "# Generated by experiments/report/published_instances.py.",
        "#",
        "# Degrees are bag coverage at rho = 0.5, measured on the loaded instance. A dash means the",
        "# inclusion was not reported at that threshold, which for the last MovieLens row is the",
        "# result rather than a gap.",
        "",
    ]

    for title, directory, results_name, expectations in INSTANCES:
        export = work / directory / "metalevel"
        results = work / directory / results_name
        lines.append("## " + title)
        if not export.exists() or not results.exists():
            lines += ["  SKIPPED: " + str(export) + " or " + str(results) + " missing", ""]
            continue
        scopes, extractors, observations = catalog_summary(export)
        found = inclusions(results)
        lines.append("  %d scopes, %d extractors, %d observations, %d inclusions at rho = 0.5"
                     % (scopes, extractors, observations, len(found)))
        lines.append("")
        for dependent, referenced, description in expectations:
            degree = found.get((dependent, referenced))
            lines.append("  %-58s %s" % (short(dependent) + " -> " + short(referenced),
                                         "%.4f" % degree if degree is not None else "not reported"))
            lines.append("      " + description)
        lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8")
    print("written to " + str(out))
    return 0


def short(name):
    """Trims the qualifying prefixes that make a name too wide to line up, losing nothing."""
    return (name.replace("listenbrainz.listens@track_metadata.additional_info", "listens@ta")
                .replace("listenbrainz.", "")
                .replace("neo4j:WikidataFilm@movielens_movie_ids.movielens_movie_ids",
                         "WikidataFilm@movielens_movie_ids")
                .replace("neo4j:", ""))


if __name__ == "__main__":
    sys.exit(main())
