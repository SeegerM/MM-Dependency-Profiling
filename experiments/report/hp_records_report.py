"""Regenerates paper/tables/hp-records.txt for every instance the profile is reported on.

The inter-model FD input is optional per instance; without a pipeline run the redundant-extractor
kind is absent rather than zero.

usage: hp_records_report.py [--work=$WORK_ROOT] [--out=paper/tables/hp-records.txt]
"""
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "lib"))
import paths  # noqa: E402

HERE = Path(__file__).resolve().parents[2]
RECORDS = HERE / "profile" / "hp_records.py"

# (heading, exportDir, indResultDir, extra flags)
INSTANCES = [
    ("UniBench, rho = 0.5",
     "unibench/metalevel", "unibench/meta-results-0.5",
     ["--rho=0.5", "--similarity={work}/unibench/p50-sim",
      "--genuineness={work}/unibench/genuineness-0.5.json",
      "--intermodel={work}/unibench/pipeline.json"]),
    ("TPC-H, rho = 1.0 (derivable-extractor is 0: TPC-H is normalized; "
     "redundant-extractor is 0: no predicate survives stage 2)",
     "mm_tpch/metalevel", "compare/mm-1.0/ind-results",
     ["--rho=1.0", "--genuineness={work}/mm_tpch/genuineness.json",
      "--intermodel={work}/mm_tpch/pipeline.json"]),
    ("MusicBrainz (full), rho = 1.0 -- at scale; no FD/UCC dumps at 1,196 extractors",
     "musicbrainz-full/metalevel", "musicbrainz-full/eq-1.0",
     ["--rho=1.0", "--genuineness={work}/musicbrainz-full/genuineness.json"]),
    # The only instance whose store assignment was designed by its own authors.
    ("MMSBench-Net (coms), rho = 1.0 -- externally designed across the three models",
     "coms/metalevel", "coms/meta-results-1.0",
     ["--rho=1.0", "--similarity={work}/coms/sim",
      "--genuineness={work}/coms/genuineness.json"]),
    # The three published multi-source instances. No FD or UCC dumps at these row counts, so the
    # FD- and UCC-derived kinds are absent rather than zero.
    ("MovieLens + TMDB + Wikidata, rho = 0.5 -- three independently maintained sources",
     "movielens/metalevel", "movielens/meta-results-0.5",
     ["--rho=0.5", "--genuineness={work}/movielens/genuineness.json"]),
    ("Helsinki UDBMS Patent, rho = 0.5 -- one publisher's tables and citation graph",
     "hpatent/metalevel", "hpatent/meta-results-0.5",
     ["--rho=0.5", "--genuineness={work}/hpatent/genuineness.json"]),
    ("ListenBrainz, rho = 0.5 -- three dumps joined by an identifier none of them declares",
     "listenbrainz/metalevel", "listenbrainz/meta-results-0.5",
     ["--rho=0.5", "--genuineness={work}/listenbrainz/genuineness.json"]),
]


def flag(name, default):
    return next((a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith(f"--{name}=")), default)


def main():
    work = flag("work", str(paths.WORK_ROOT))
    out = Path(flag("out", str(HERE / "paper" / "tables" / "hp-records.txt")))

    blocks = [
        "# Heterogeneity Profile as a record set (INDs, UCCs and FDs; typed evidence per kind).",
        "# Generated by experiments/report/hp_records_report.py.",
        "#",
        "# candidate-key and join-candidate are supporting evidence rather than heterogeneity",
        "# findings, and are excluded from the finding total reported in the paper.",
        "",
    ]

    for heading, export, results, extra in INSTANCES:
        export_dir, result_dir = Path(work) / export, Path(work) / results
        if not export_dir.exists() or not result_dir.exists():
            blocks += [f"## {heading}", "  SKIPPED: export or results missing", ""]
            continue
        argv = [sys.executable, str(RECORDS), str(export_dir), str(result_dir), "--top=10"]
        argv += [a.format(work=work) for a in extra
                 if not a.startswith(("--similarity=", "--genuineness=", "--intermodel="))
                 or Path(a.split("=", 1)[1].format(work=work)).exists()]
        # Transformation-aware INDs, when transform_discovery_all.sh has run for the instance.
        transforms = Path(work) / export.split("/")[0] / "transforms.json"
        if transforms.exists():
            argv.append(f"--transforms={transforms}")
        done =subprocess.run(argv, capture_output=True, text=True, cwd=str(HERE))
        if done.returncode != 0:
            blocks += [f"## {heading}", "  FAILED:", done.stderr.strip()[-800:], ""]
            continue
        blocks += [f"## {heading}", done.stdout.rstrip(), ""]

    out.write_text("\n".join(blocks), encoding="utf-8")
    print(f"written to {out}")


if __name__ == "__main__":
    main()
