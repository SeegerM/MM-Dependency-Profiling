"""The inter-model FD qualification table, generated from each instance's own pipeline output.

`removed by utilisation` is the difference between the counts at u = 0 and at u (stage 2b, a
reporting filter against subset-induced scopes). `qualified inter-model FDs` is the count at u.

usage: intermodel_table.py [--work=$WORK_ROOT] [--out=paper/tables/intermodel-table.txt]
                           [--tex=paper/tables/intermodel-table.tex]
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "lib"))
import paths  # noqa: E402

HERE = Path(__file__).resolve().parents[2]

# The instances the pipeline can run on at all: an inter-model FD needs two stores to be inter-model.
INSTANCES = [("TPC-H", "mm_tpch"), ("UniBench", "unibench"), ("IMDB", "imdb"),
             ("MusicBrainz", "musicbrainz"), ("MovieLens", "movielens"),
             ("Helsinki Patent", "hpatent"), ("Helsinki Person", "hperson"),
             ("Helsinki Film", "hfilm"), ("ListenBrainz", "listenbrainz"),
             ("MMSBench-Net", "coms")]

ROWS = [
    ("cross-store inclusions", "candidates"),
    ("qualified references", "qualified"),
    ("join-induced scopes", "scopes"),
    ("cross-side FDs", "cross_side"),
    ("entailed", "entailed"),
    ("determinant from both sides", "mixed"),
    ("non-entailed, one side determining", "non_entailed"),
    ("removed by gpdep", "accidental"),
    ("removed by utilisation", None),
    ("qualified inter-model FDs", None),
]


def flag(name, default):
    return next((a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--" + name + "=")),
                default)


def load(work, directory):
    path = work / directory / "pipeline.json"
    if not path.exists():
        return None
    blob = json.loads(path.read_text(encoding="utf-8"))
    floor = blob.get("u", 0.1)
    findings = blob.get("findings", [])
    blob["at_u"] = sum(1 for f in findings if f["utilisation"] >= floor)
    # counts["inter_model"] is the count before the utilisation filter; the difference is stage 2b.
    blob["removed_by_u"] = blob["counts"]["inter_model"] - blob["at_u"]
    return blob


def value(blob, key, label):
    if label == "removed by utilisation":
        return blob["removed_by_u"]
    if label == "qualified inter-model FDs":
        return blob["at_u"]
    return blob["counts"].get(key, 0)


def main():
    work = Path(flag("work", str(paths.WORK_ROOT)))
    out = Path(flag("out", str(HERE / "paper" / "tables" / "intermodel-table.txt")))
    tex = Path(flag("tex", str(HERE / "paper" / "tables" / "intermodel-table.tex")))

    blobs = [(label, load(work, directory)) for label, directory in INSTANCES]
    present = [(label, blob) for label, blob in blobs if blob is not None]
    absent = [label for label, blob in blobs if blob is None]
    floors = {blob.get("u") for _, blob in present}

    lines = [
        "# Inter-model FD qualification, every instance the pipeline was run on.",
        "# Generated by experiments/report/intermodel_table.py from each run's pipeline.json.",
        "#",
        "# Only the last row is reported as inter-model redundancy evidence. 'removed by",
        "# utilisation' is stage 2b, a reporting filter against subset-induced scopes, and is not",
        "# a condition for a predicate being a reference.",
        "",
        "  u = %s" % ", ".join(str(f) for f in sorted(floors)),
        "",
        "  %-36s%s" % ("stage", "".join("%16s" % label for label, _ in present)),
    ]
    for label, key in ROWS:
        lines.append("  %-36s%s" % (label, "".join("%16s" % format(value(blob, key, label), ",")
                                                   for _, blob in present)))
    if absent:
        lines += ["", "  not run: %s" % ", ".join(absent)]

    # Per instance: the stage it stops at and the rejection reasons.
    lines += ["", "## where each instance stops, and why"]
    for label, blob in present:
        rejected = blob.get("rejected", {})
        reasons = ", ".join("%s %d" % (r.split(") ", 1)[-1], n)
                            for r, n in sorted(rejected.items(), key=lambda kv: -kv[1]))
        lines.append("  %-18s %d candidates, %d qualified, %d reported%s"
                     % (label, blob["counts"]["candidates"], blob["counts"]["qualified"],
                        blob["at_u"], ("   rejected: " + reasons) if reasons else ""))

    lines += ["", "## the FDs themselves"]
    for label, blob in present:
        floor = blob.get("u", 0.1)
        surviving = [f for f in blob.get("findings", []) if f["utilisation"] >= floor]
        if not surviving:
            continue
        lines.append("  %s (%d)" % (label, len(surviving)))
        for entry in sorted(surviving, key=lambda f: -f["gpdep"])[:20]:
            lines.append("    gpdep %.4f  %-38s over %s"
                         % (entry["gpdep"], entry["fd"], entry["predicate"]))

    text = "\n".join(lines) + "\n"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")

    # The LaTeX table body.
    columns = "l" + "r" * len(present)
    body = ["\\begin{tabular}{%s}" % columns, "\\toprule",
            "stage & " + " & ".join(label for label, _ in present) + " \\\\", "\\midrule"]
    for label, key in ROWS[:-1]:
        body.append("%s & %s \\\\" % (label, " & ".join("%s" % format(value(blob, key, label), ",")
                                                        for _, blob in present)))
    body += ["\\midrule",
             "\\textbf{qualified inter-model FDs} & "
             + " & ".join("\\textbf{%d}" % blob["at_u"] for _, blob in present) + " \\\\",
             "\\bottomrule", "\\end{tabular}"]
    tex.write_text("\n".join(body) + "\n", encoding="utf-8")

    print(text)
    print("written to %s and %s" % (out, tex))


if __name__ == "__main__":
    main()
