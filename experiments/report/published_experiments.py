"""Collect the evaluation's existing experiments across every instance into one table.

Covers strategy independence, key prefiltering, n-ary discovery, inter-model FDs, the Helsinki
Patent component ablation, scalability and null calibration. The per-instance thresholds are those
selected in paper/tables/threshold-choice.txt.

usage: published_experiments.py [--work=$WORK_ROOT]
                                [--out=paper/tables/published-experiments.txt]
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "lib"))
import paths  # noqa: E402

HERE = Path(__file__).resolve().parents[2]
TRAILING_COMMA = re.compile(r",\s*([}\]])")

# (label, instance directory, threshold)
INSTANCES = [("TPC-H", "mm_tpch", 1.00),
             ("UniBench", "unibench", 0.50),
             ("IMDB", "imdb", 1.00),
             ("MusicBrainz", "musicbrainz", 1.00),
             ("MovieLens", "movielens", 0.85),
             ("Helsinki Patent", "hpatent", 0.80),
             ("ListenBrainz", "listenbrainz", 0.90)]


def flag(name, default):
    return next((a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--" + name + "=")),
                default)


def text_of(path):
    return path.read_text(encoding="utf-8", errors="replace") if path.exists() else ""


def inclusions(results):
    """{(dependent, referenced)} from a result directory, or None when it is not there."""
    path = results / "1-ary_pINDs.json"
    if not path.exists():
        return None
    text = TRAILING_COMMA.sub(r"\1", path.read_text(encoding="utf-8"))
    found = set()
    for relation in json.loads(text):
        for pind in relation.get("pINDs", []):
            dependent = relation["relation"] + "." + ".".join(pind["dependant"])
            for ref in pind["referenced"]:
                found.add((dependent, ref["relation"] + "." + ".".join(ref["attribute"])))
    return found


def last_match(pattern, text, group=1):
    found = re.findall(pattern, text)
    return found[-1] if found else None


def main():
    work = Path(flag("work", str(paths.WORK_ROOT)))
    out = Path(flag("out", str(HERE / "paper" / "tables" / "published-experiments.txt")))

    lines = [
        "# The evaluation's own experiments, run on every instance rather than on the one each",
        "# was written against.",
        "# Generated by experiments/report/published_experiments.py.",
        "",
        "## strategy independence: four validation strategies, one result set",
        "  %-18s %8s %10s %s" % ("instance", "pINDs", "strategies", "digest"),
    ]
    for label, directory, _ in INSTANCES:
        body = text_of(work / directory / "strategy.txt")
        digest = last_match(r"digest ([0-9a-f]+)", body)
        # Rows read "<strategy>  8,968ms  29  <digest>"; the strategy names carry spaces and
        # parentheses, so the anchor is the timing rather than the name.
        count = last_match(r"[\d,]+ms\s+(\d+)\s+[0-9a-f]{6,}", body)
        agree = "4 agree" if digest else "not run"
        lines.append("  %-18s %8s %10s %s"
                     % (label, count or "-", agree, digest or "-"))
    lines += [
        "  The physical strategy is a property of the run and not of the data, which is what these",
        "  digests say on instances that were not available when the claim was made.",
        "",
        "## prefiltering by a discovered key: what the ranking costs in recall",
        "  %-18s %10s %10s %10s %s" % ("instance", "inclusions", "kept", "reduction", "recall"),
    ]
    for label, directory, _ in INSTANCES:
        body = text_of(work / directory / "prefilter.txt")
        row = last_match(r"referenced side is a key\s+([\d,]+)\s+([\d.]+)x\s+(\d+/\d+)\s+(\d+)%",
                         body)
        total = last_match(r"all inclusions\s+([\d,]+)", body)
        if row:
            kept, reduction, recall, percent = row
            lines.append("  %-18s %10s %10s %9sx %s (%s%%)"
                         % (label, total or "-", kept, reduction, recall, percent))
        else:
            lines.append("  %-18s %10s %10s %10s %s" % (label, total or "-", "-", "-", "not run"))
    lines += [
        "  Requiring the referenced side to be a discovered key is the cheapest useful filter and",
        "  the one whose cost is visible: on ListenBrainz it drops the inclusion whose referenced",
        "  side is deliberately not a key, which is the trade rather than a defect.",
        "",
        "## n-ary discovery at arity 2",
        "  %-18s %10s %10s" % ("instance", "unary", "binary"),
    ]
    for label, directory, _ in INSTANCES:
        body = text_of(work / directory / "nary.log")
        counts = re.findall(r"Found (\d+) pINDs", body)
        lines.append("  %-18s %10s %10s"
                     % (label, counts[0] if counts else "-",
                        counts[1] if len(counts) > 1 else "-"))
    lines += [
        "",
        "## inter-model functional dependencies over join-induced scopes",
    ]
    for label, directory, _ in INSTANCES:
        path = work / directory / "pipeline.json"
        if not path.exists():
            lines.append("  %-18s not run" % label)
            continue
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            lines.append("  %-18s unreadable" % label)
            continue
        counts = data.get("counts", {})
        floor = float(data.get("u", 0.1))
        findings = [entry for entry in data.get("findings", [])
                    if float(entry.get("utilisation", 0.0)) >= floor]
        lines.append("  %-18s %d inter-model FD(s) from %d qualified predicate(s) of %d candidates"
                     % (label, len(findings),
                        counts.get("qualified", 0), counts.get("candidates", 0)))
        for entry in findings[:3]:
            gpdep = entry.get("gpdep")
            lines.append("      %s   over %s"
                         % (entry.get("fd", "?"), entry.get("predicate", "?")))
            if gpdep is not None:
                lines.append("        gpdep %.4f, utilisation %.4f"
                             % (gpdep, entry.get("utilisation", float("nan"))))
    lines += [
        "",
        "## component ablation: what the edge scope contributes on Helsinki Patent",
    ]
    scoped = inclusions(work / "hpatent" / "meta-results-0.5")
    # Produced by ExportSources --flat; see that class's usage note.
    flat = inclusions(work / "hpatent" / "results-flat")
    oracle_path = work / "hpatent" / "ground_truth.json"
    if scoped and flat and oracle_path.exists():
        oracle = json.loads(oracle_path.read_text(encoding="utf-8"))["dependencies"]
        keys = [(d["dependent"], d["referenced"]) for d in oracle]
        in_scoped = [k for k in keys if k in scoped]
        in_flat = [k for k in keys if k in flat]
        lines += [
            "  %-38s %10s %10s" % ("", "scoped", "no edges"),
            "  %-38s %10d %10d" % ("inclusions reported", len(scoped), len(flat)),
            "  %-38s %8d/%-2d %8d/%-2d" % ("oracle recovered", len(in_scoped), len(keys),
                                           len(in_flat), len(keys)),
        ]
        lost = [k for k in keys if k in scoped and k not in flat]
        for left, right in lost:
            lines.append("      lost without it: %s -> %s" % (left, right))
        lines += [
            "  A graph store read as one flat relation per label has no way to express a",
            "  relationship's endpoints, so both citation endpoints disappear -- including the",
            "  0.8460 one, which is the finding this instance is here for. The scoped lift is not",
            "  a better ranking of the same candidates; those candidates do not exist without it.",
        ]
    else:
        lines.append("  not run: export with ExportSources --flat and discover, then re-run")

    lines += [
        "",
        "## scalability: what an instance of this size costs",
        "  %-18s %13s %11s %12s %10s" % ("instance", "observations", "extractors",
                                         "discovery ms", "inclusions"),
    ]
    for label, directory, _ in INSTANCES:
        catalog_path = work / directory / "metalevel" / "catalog.json"
        if not catalog_path.exists():
            lines.append("  %-18s not present" % label)
            continue
        catalog = json.loads(catalog_path.read_text(encoding="utf-8"))
        observations = sum(e["rows"] for e in catalog)
        extractors = sum(e["columns"] for e in catalog)
        body = ""
        for name in ("ind-1.0.log", "ind.log", "ind-0.5.log"):
            candidate = work / directory / name
            if candidate.exists():
                body = text_of(candidate)
                break
        milliseconds = last_match(r"discovery took (\d+) ms", body)
        found = last_match(r"Found (\d+) pINDs", body)
        lines.append("  %-18s %13s %11s %12s %10s"
                     % (label, format(observations, ","), format(extractors, ","),
                        format(int(milliseconds), ",") if milliseconds else "-", found or "-"))
    lines += [
        "  Extractor count drives validation and volume drives the export, which is the split the",
        "  relational corpora already showed; these instances sit either side of it without",
        "  changing the picture.",
        "",
        "## null calibration: the comparison domains the chance correction conditions on",
    ]
    for label, directory, _ in INSTANCES:
        body = text_of(work / directory / "null-calibration.txt")
        split = last_match(r"sampled cells are ([\d.]+% numeric, [\d.]+% textual)", body)
        lines.append("  %-18s %s" % (label, split or "not run"))
    lines += [
        "  A score conditioned on the domain is one an extractor cannot earn against values it",
        "  could never have been compared with; these are the splits that conditioning uses.",
    ]

    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("written to " + str(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
