"""Scores TPC-H at the reported threshold (rho = 1) and at the relaxation rho = 0.95.

Every run is scored by oracle_manifest.score. For each run the report lists the oracle entries no
live inclusion recovers, and the partial degree of every oracle entry.

usage: tpch_threshold.py [--work=$WORK_ROOT] [--out=paper/tables/tpch-threshold.txt]
       [--run=<label>=<results dir below WORK_ROOT>]...
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(HERE / "experiments" / "lib"))
sys.path.insert(0, str(HERE / "experiments" / "report"))
import dependency_key  # noqa: E402
import oracle_manifest  # noqa: E402
import paths  # noqa: E402

TRAILING_COMMA = re.compile(r",\s*([}\]])")

# (label, results below WORK_ROOT). The first is the run Table 4 reports.
RUNS = [
    ("rho = 1.0 (Table 4)", "compare/mm-1.0/ind-results"),
    ("rho = 0.95", "compare/mm-0.95-rerun/ind-results"),
]


def flag(name, default=None):
    prefix = f"--{name}="
    return next((a[len(prefix):] for a in sys.argv[1:] if a.startswith(prefix)), default)


def degrees(results):
    """Partial degree per (dependent, referenced) key, as SPIND reported it."""
    text = TRAILING_COMMA.sub(r"\1", (results / "1-ary_pINDs.json").read_text(encoding="utf-8"))
    out = {}
    for relation in json.loads(text):
        for pind in relation.get("pINDs", []):
            dependent = relation["relation"] + "." + ".".join(pind["dependant"])
            for ref in pind["referenced"]:
                referenced = ref["relation"] + "." + ".".join(ref["attribute"])
                out[dependency_key.key(dependent, referenced)] = float(ref["partialDegree"])
    return out


def main():
    work = Path(flag("work", str(paths.WORK_ROOT)))
    out = Path(flag("out", str(HERE / "paper" / "tables" / "tpch-threshold.txt")))
    runs = RUNS + [tuple(a[len("--run="):].rsplit("=", 1))
                   for a in sys.argv[1:] if a.startswith("--run=")]

    export = work / "mm_tpch" / "metalevel"
    oracle = json.loads((work / "mm_tpch" / "ground_truth.json").read_text(encoding="utf-8"))
    statable = [e for e in oracle["dependencies"]
                if "dependent" in e and int(e.get("arity", 1)) == 1]
    filled = oracle_manifest.support_counts(export)

    lines = [
        "# TPC-H recall by threshold, scored by oracle_manifest.score.",
        "# Generated by experiments/report/tpch_threshold.py.",
        "",
        "  %-22s %6s %8s %10s   %s" % ("run", "raw", "non-vac", "recovered", "results"),
    ]
    reports = []
    for label, rel in runs:
        results = work / rel
        if not (results / "1-ary_pINDs.json").exists():
            lines.append("  %-22s  missing: %s" % (label, results))
            continue
        raw, live, recovered, missed = oracle_manifest.score(export, results, statable, filled)
        lines.append("  %-22s %6d %8d %10s   %s" % (label, raw, live,
                                                  "%d/%d" % (recovered, len(statable)), rel))
        reports.append((label, results, missed))

    for label, results, missed in reports:
        found = degrees(results)
        lines += ["", "## %s: partial degree per oracle entry" % label]
        for entry in statable:
            key = dependency_key.key(entry["dependent"], entry["referenced"])
            degree = found.get(key)
            lines.append("  %-44s -> %-34s %s" % (
                entry["dependent"], entry["referenced"],
                "not reported" if degree is None else "%.6f" % degree))
        if missed:
            lines.append("  missed: " + ", ".join(e["dependent"] for e in missed))

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print("written to", out)


if __name__ == "__main__":
    main()
