"""Scores discovered union scopes on the two natural instances: MMSBench-Net and LDBC SNB.

For each instance, exports of the same data are discovered with SPIND at rho = 1 and scored by
oracle_manifest.score:

  without unions   the export with no union scope
  declared union   MMSBench-Net only: the six-label device union written into ExportComs.java
  discovered       the export without unions plus what experiments/run/discover_scopes.py proposes

An oracle entry referencing a union names it (`coms.device-union`, `ldbc.place-union`, ...). For
the discovered export that name is mapped to the discovered union with the same member scopes, so
the comparison asks whether discovery found the population the oracle refers to, not whether it
guessed a name. The union's members come from the declared export (MMSBench-Net) or from the
oracle's own union declarations (LDBC, built by experiments/datasets/build_ldbc.py). A union the
oracle declares but no reference needs (LDBC's Message) must not be proposed; the report says
whether it was.

usage: scope_discovery.py [--work=$WORK_ROOT] [--out=paper/tables/scope-discovery.txt]
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(HERE / "experiments" / "lib"))
sys.path.insert(0, str(HERE / "experiments" / "report"))
import oracle_manifest  # noqa: E402
import paths  # noqa: E402

# (label, instance directory, settings as (label, export, IND results))
INSTANCES = [
    ("MMSBench-Net", "coms", [
        ("without unions", "metalevel-before-union", "meta-results-1.0-before-union"),
        ("declared union", "metalevel", "meta-results-1.0"),
        ("discovered", "metalevel-discovered", "meta-results-1.0-discovered"),
    ]),
    ("LDBC SNB", "ldbc", [
        ("without unions", "metalevel", "meta-results-1.0"),
        ("discovered", "metalevel-discovered", "meta-results-1.0-discovered"),
    ]),
]


def flag(name, default=None):
    prefix = f"--{name}="
    return next((a[len(prefix):] for a in sys.argv[1:] if a.startswith(prefix)), default)


def unions(export):
    catalog = json.loads((export / "catalog.json").read_text(encoding="utf-8"))
    return {e["relation"]: frozenset(e["members"]) for e in catalog if e.get("members")}


def statable(entries, export):
    present = {oracle_manifest._identity(name) for name in oracle_manifest.support_counts(export)}
    return [e for e in entries
            if oracle_manifest._identity(e["dependent"]) in present
            and oracle_manifest._identity(e["referenced"]) in present]


def oracle_unions(work, oracle):
    """Union name -> (member scopes, demanded?), from the oracle or else the declared export."""
    if oracle.get("unions"):
        return {u["name"]: (frozenset(u["members"]), u.get("demanded", True)) for u in oracle["unions"]}
    return {name: (members, True) for name, members in unions(work / "metalevel").items()}


def main():
    root = Path(flag("work", str(paths.WORK_ROOT)))
    out = Path(flag("out", str(HERE / "paper" / "tables" / "scope-discovery.txt")))
    lines = [
        "# Union scopes on the natural instances: none, declared by hand, discovered from the data.",
        "# Generated by experiments/report/scope_discovery.py; scored by oracle_manifest.score.",
    ]
    for instance, directory, settings in INSTANCES:
        work = root / directory
        if not (work / "ground_truth.json").exists():
            lines += ["", f"## {instance}: no instance at {work}"]
            continue
        oracle_doc = json.loads((work / "ground_truth.json").read_text(encoding="utf-8"))
        oracle = [e for e in oracle_doc["dependencies"] if "dependent" in e]
        expected = oracle_unions(work, oracle_doc)
        lines += ["", f"## {instance}",
                  "  %-16s %7s %9s %8s %10s   %s" % ("setting", "unions", "statable", "non-vac",
                                                     "recovered", "export")]
        notes = []
        for label, export_rel, results_rel in settings:
            export, results = work / export_rel, work / results_rel
            if not (results / "1-ary_pINDs.json").exists():
                lines.append("  %-16s missing %s" % (label, results))
                continue
            found = unions(export)
            entries = oracle
            if label == "discovered":
                rename = {}
                for name, (members, demanded) in expected.items():
                    match = [d for d, m in found.items() if m == members]
                    rename[name] = match[0] if match else None
                    verdict = ("found as " + match[0]) if match else "not proposed"
                    notes.append("  %s (%d members, %s): %s%s" % (
                        name, len(members), "demanded" if demanded else "not demanded", verdict,
                        "" if bool(match) == demanded else "  <- WRONG"))
                spurious = [d for d, m in found.items() if m not in {v[0] for v in expected.values()}]
                for d in spurious:
                    notes.append("  proposed beyond the oracle: %s over %s" % (d, ", ".join(sorted(found[d]))))
                entries = []
                for e in oracle:
                    relation = e["referenced"].rsplit(".", 1)[0]
                    if rename.get(relation):
                        e = dict(e, referenced=rename[relation] + "." + e["referenced"].rsplit(".", 1)[1])
                    entries.append(e)
            judged = statable(entries, export)
            raw, live, recovered, missed = oracle_manifest.score(export, results, judged)
            lines.append("  %-16s %7d %9s %8d %10s   %s" % (
                label, len(found), "%d/%d" % (len(judged), len(entries)), live,
                "%d/%d" % (recovered, len(entries)), export_rel))
            for e in missed:
                notes.append("  %s: missed %s -> %s" % (label, e["dependent"], e["referenced"]))
        if notes:
            lines += ["  unions and misses:"] + ["  " + n for n in notes]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print("written to", out)


if __name__ == "__main__":
    main()
