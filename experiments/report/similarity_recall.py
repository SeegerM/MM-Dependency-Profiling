"""Recall of the representation-aware runs behind Table 4's section-sign footnote.

Table 4 reports the equality/partial run of each instance. Two of its misses are representation
differences, and a comparison relation other than equality recovers them:

  MovieLens        the IMDb identifier with and without its registry prefix (`0114709`,
                   `tt0114709`): the registry-prefix comparison recovers both directions
  Helsinki Person  page titles with spaces against identifiers with underscores: edit distance 1
                   reaches it, because long name strings are far apart (unlike dense numeric ids)

Each run is scored exactly as the manifest scores the reported one (oracle_manifest.score), over
the same statable entries, and printed next to the reported run for comparison.

usage: similarity_recall.py [--work=$WORK_ROOT] [--out=paper/tables/similarity-recall.txt]
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(HERE / "experiments" / "lib"))
sys.path.insert(0, str(HERE / "experiments" / "report"))
import paths  # noqa: E402
import oracle_manifest as om  # noqa: E402

# (instance, [(setting, result directory)])
RUNS = [
    ("movielens", [("equality/partial, rho 0.5 (reported)", "meta-results-0.5"),
                   ("edit distance 1, rho 0.5", "sim-t1"),
                   ("registry prefix, rho 0.5", "sim-prefix-0.5")]),
    ("hperson", [("equality/partial, rho 0.5 (reported)", "meta-results-0.5/ind-results"),
                 ("edit distance 1, rho 0.5", "sim-t1-0.5"),
                 ("separator-normalised, rho 0.5", "sim-normalised-0.5")]),
]


def flag(name, default):
    return next((a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith(f"--{name}=")), default)


def main():
    work = Path(flag("work", str(paths.WORK_ROOT)))
    out = Path(flag("out", str(HERE / "paper" / "tables" / "similarity-recall.txt")))
    lines = ["# Recall under representation-aware comparison relations (Table 4, section-sign footnote).",
             "# Generated by experiments/report/similarity_recall.py; scored by oracle_manifest.score.",
             "# 'reported' counts every inclusion the run reports; the oracle is not exhaustive here, so",
             "# the growth over the reported run shows how much a relation adds beyond the oracle."]
    for instance, settings in RUNS:
        export = work / instance / "metalevel"
        oracle = [e for e in json.loads((work / instance / "ground_truth.json").read_text(encoding="utf-8"))["dependencies"]
                  if "dependent" in e and e.get("oracle_kind") != "correspondence" and int(e.get("arity", 1)) == 1]
        filled = om.support_counts(export)
        lines += ["", f"## {instance}", "  %-40s %9s %10s   %s" % ("comparison relation", "reported", "recovered", "missed")]
        for setting, run in settings:
            results = work / instance / run
            if not (results / "1-ary_pINDs.json").exists():
                lines.append("  %-40s missing %s" % (setting, results))
                continue
            _, live, recovered, missed = om.score(export, results, oracle, filled)
            lines.append("  %-40s %9d %10s   %s" % (setting, live, "%d/%d" % (recovered, len(oracle)),
                                                    "; ".join(e["dependent"] + " -> " + e["referenced"] for e in missed) or "-"))
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print("written to", out)


if __name__ == "__main__":
    main()
