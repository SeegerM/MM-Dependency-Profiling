"""Selected Heterogeneity Profile records: one worked example per kind, drawn across the corpora.

Selection is by rule: a link record is eligible only if the link is in the instance's oracle; for
non-link kinds, generated payload extractors are excluded and the highest-scoring record is taken.
Instances are preferred in INSTANCES order, spread so that each kind uses a distinct instance where
possible. The kind's record count on that instance is printed beside each exemplar.

usage: hp_exemplars.py [--work=$WORK_ROOT] [--out=paper/tables/hp-exemplars.txt]
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(HERE / "experiments" / "lib"))
import paths  # noqa: E402
import dependency_key  # noqa: E402

# Preference order: instances whose layout we did not choose come first.
INSTANCES = [
    ("MMSBench-Net", "coms"),
    ("Helsinki Patent", "hpatent"),
    ("MovieLens", "movielens"),
    ("ListenBrainz", "listenbrainz"),
    ("MusicBrainz", "musicbrainz-full"),
    ("UniBench", "unibench"),
    ("TPC-H", "mm_tpch"),
]

# Supporting evidence rather than heterogeneity findings; excluded from the paper's totals and so
# from this table.
EVIDENCE_ONLY = {"candidate-key", "join-candidate"}


def flag(name, default=None):
    return next((a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--" + name + "=")),
                default)


def oracle_keys(path):
    """The instance's oracle as comparable dependency identities, empty when it has none."""
    if not Path(path).exists():
        return set()
    entries = json.loads(Path(path).read_text(encoding="utf-8"))["dependencies"]
    return {dependency_key.key(e["dependent"], e["referenced"])
            for e in entries if "dependent" in e}


def is_oracle_link(record, oracle):
    subject = record.get("subject") or {}
    if "dependent" not in subject or "referenced" not in subject:
        return False
    return dependency_key.key(subject["dependent"], subject["referenced"]) in oracle


def generated_subject(record):
    """Whether a record is about MMSBench-Net's generated payload properties.

    Its device nodes and log documents carry meaningless properties named key0..key9, which
    dominate that instance's profile by count.
    """
    text = json.dumps(record.get("subject") or {})
    return any(("key%d" % i) in text for i in range(10))


def subject_of(record):
    subject = record.get("subject") or {}
    if "dependent" in subject:
        return "%s -> %s" % (subject["dependent"], subject.get("referenced", "?"))
    for key in ("extractor", "scope", "extractors"):
        if key in subject:
            value = subject[key]
            return ", ".join(value) if isinstance(value, list) else str(value)
    return json.dumps(subject)[:60]


def measurement_of(record):
    """The number the record carries, named. Kinds measure different things by design."""
    for field, label in (("strength", "strength"), ("value", "value")):
        if record.get(field) is not None:
            return "%s %.4f" % (label, record[field])
    return "-"


def main():
    work = Path(flag("work", str(paths.WORK_ROOT)))
    out = Path(flag("out", str(HERE / "paper" / "tables" / "hp-exemplars.txt")))

    by_kind = {}
    seen_instances = []
    for label, directory in INSTANCES:
        path = work / directory / "hp-records.jsonl"
        if not path.exists():
            continue
        seen_instances.append(label)
        records = [json.loads(line) for line in path.open(encoding="utf-8") if line.strip()]
        oracle = oracle_keys(work / directory / "ground_truth.json")

        kinds = {r.get("kind") for r in records} - EVIDENCE_ONLY - {None}
        for kind in kinds:
            same = [r for r in records if r.get("kind") == kind]
            linked = [r for r in same if is_oracle_link(r, oracle)]
            pool = linked if linked else [r for r in same if not generated_subject(r)]
            if not pool:
                continue
            pool.sort(key=lambda r: (-(r.get("genuineness") or 0.0),
                                     -(r.get("strength") or 0.0)))
            by_kind.setdefault(kind, {})[label] = (pool[0], len(same), bool(linked))

    lines = [
        "# One Heterogeneity Profile record per kind, chosen by rule rather than by eye.",
        "# Generated by experiments/report/hp_exemplars.py.",
        "#",
        "# The instance is the least-arranged one carrying that kind: MMSBench-Net's layout was",
        "# designed by its own authors, the publisher-assembled instances were assembled by their",
        "# publishers, and the converted and seeded corpora were laid out by us. Within an instance",
        "# the exemplar is the record the profile itself orders first, by genuineness.",
        "",
        "  %-22s %-16s %-50s %-18s %5s  %s"
        % ("kind", "instance", "subject", "measurement", "of", "backed by"),
    ]
    # Spread across instances: each kind takes an instance not yet used where one qualifies, and
    # kinds with the fewest qualifying instances choose first.
    used = set()
    chosen = {}
    for kind in sorted(by_kind, key=lambda k: (len(by_kind[k]), k)):
        candidates = [(label, directory) for label, directory in INSTANCES
                      if label in by_kind[kind]]
        pick = next((label for label, _ in candidates if label not in used), None)
        if pick is None:
            pick = candidates[0][0]
        else:
            used.add(pick)
        chosen[kind] = pick

    for kind in sorted(by_kind):
        label = chosen[kind]
        record, total, from_oracle = by_kind[kind][label]
        lines.append("  %-22s %-16s %-50s %-18s %5d  %s"
                     % (kind, label, subject_of(record)[-50:],
                        measurement_of(record), total,
                        "oracle" if from_oracle else "-"))

    lines += [
        "",
        "## instances read",
        "  " + ", ".join(seen_instances),
        "",
        "## reading",
        "  'of' is how many records of that kind the instance carries, so an exemplar can be seen",
        "  against its population rather than in isolation. A kind absent here is absent from every",
        "  profile generated, not merely unselected.",
    ]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[8:]))
    print("\nwritten to " + str(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
