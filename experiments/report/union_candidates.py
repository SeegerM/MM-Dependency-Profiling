"""What the union proposer fires on across every instance, i.e. the selectivity of the rule.

`experiments/run/propose_unions.py` derives union scopes from an export without reading an oracle;
this reports where it fires, including instances where no union is expected.

usage: union_candidates.py [--work=$WORK_ROOT] [--out=paper/tables/union-candidates.txt]
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(HERE / "experiments" / "run"))

from propose_unions import groups, load, proposals  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "lib"))
import paths  # noqa: E402

INSTANCES = [
    ("TPC-H", "mm_tpch/metalevel"),
    ("UniBench", "unibench/metalevel"),
    ("IMDB", "imdb/metalevel"),
    ("MovieLens", "movielens-small/metalevel"),
    ("Helsinki Patent", "hpatent-small/metalevel"),
    ("Helsinki Person", "hperson/metalevel"),
    ("Helsinki Film", "hfilm/metalevel"),
    ("ListenBrainz", "listenbrainz-small/metalevel"),
    ("MMSBench-Net", "coms-iso/metalevel"),
]


def flag(name, default=None):
    prefix = "--" + name + "="
    return next((a[len(prefix):] for a in sys.argv[1:] if a.startswith(prefix)), default)


def main():
    work = Path(flag("work", str(paths.WORK_ROOT)))
    out = Path(flag("out", str(HERE / "paper" / "tables" / "union-candidates.txt")))

    lines = [
        "# Union scopes proposed from each export alone, by experiments/run/propose_unions.py.",
        "# Generated by experiments/report/union_candidates.py.",
        "#",
        "# The rule reads extractor names and value sets. It reads no oracle, no label spelling and",
        "# no documented dependency. `groups` counts the shared-core groups of two or more scopes it",
        "# considered; `unions` counts those that survived the key and disjointness conditions.",
        "",
        "  %-18s %7s %7s %7s   %s" % ("instance", "scopes", "groups", "unions", "proposed"),
    ]
    for label, relative in INSTANCES:
        export = work / relative
        if not (export / "catalog.json").exists():
            lines.append("  %-18s %7s   export not present" % (label, "-"))
            continue
        scopes = load(export)
        found = proposals(scopes)
        first = ("%s over %s, %d members"
                 % (found[0]["sort"], found[0]["column"], len(found[0]["members"]))) if found else "--"
        lines.append("  %-18s %7d %7d %7d   %s"
                     % (label, len(scopes), len(groups(scopes)), len(found), first))
        for candidate in found:
            for member in candidate["members"]:
                lines.append("  %-18s %23s %s" % ("", "", member))

    lines += [
        "",
        "The rule fires once across nine instances, on the six device labels MMSBench-Net's",
        "generator emits, and proposes nothing on the other eight. ListenBrainz and Helsinki Film",
        "have shared-core groups and no union: their members' identifier sets overlap, which is what",
        "the disjointness condition is there to catch.",
    ]
    text = "\n".join(lines) + "\n"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(text)
    print("written to %s" % out)


if __name__ == "__main__":
    main()
