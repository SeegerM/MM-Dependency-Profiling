#!/usr/bin/env bash
# Runs the transformation-aware IND experiments:
#
#   ./experiments/run/transform_discovery_all.sh
#
#   1. discovery on every instance export (natural cases and negative control), at rho = 0.85 so
#      that MovieLens's 0.8712 registry-prefix inclusion qualifies  -> paper/tables/transform-natural.txt
#   2. the TPC-H injection benchmark                                -> paper/tables/transform-benchmark.txt
set -euo pipefail
cd "$(dirname "$0")/../.."
source config/env.sh

W="$WORK_ROOT"
{
  echo "# Transformation-aware INDs on every instance export (rho = 0.85)."
  echo "# Generated by experiments/run/transform_discovery_all.sh; no oracle is read."
  for i in mm_tpch unibench imdb musicbrainz movielens hpatent hperson hfilm huniversity listenbrainz ldbc coms; do
    export_dir="$W/$i/metalevel"
    [ "$i" = coms ] && export_dir="$W/coms/metalevel-before-union"
    [ -f "$export_dir/catalog.json" ] || { echo "  $i: no export"; continue; }
    python experiments/run/discover_transforms.py "$export_dir" --rho=0.85 \
      --out="$W/$i/transforms.txt" --json="$W/$i/transforms.json" > /dev/null
    printf '  %-13s %s\n' "$i" "$(grep -E '^(dimensions|found|time)' "$W/$i/transforms.txt" | tr -s ' ' | tr '\n' ';')"
    grep '^  ' "$W/$i/transforms.txt" | sed 's/^/    /'
  done
} | tee paper/tables/transform-natural.txt

python experiments/run/transform_benchmark.py
