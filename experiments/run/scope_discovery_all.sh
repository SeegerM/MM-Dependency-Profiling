#!/usr/bin/env bash
# Runs every scope-discovery experiment, in order:
#
#   ./experiments/run/scope_discovery_all.sh
#
#   1. MMSBench-Net: discover unions on the export without them, materialize, run SPIND at rho = 1,
#      and score against the declared union and against none (scope-discovery.txt)
#   2. the stress test, both rules against one ground truth (scope-discovery-stress.txt)
#   3. the negative control: discovery on every other instance, which documents no union
#   4. the TPC-H split benchmark with the utilisation sweep (scope-discovery-benchmark.txt)
set -euo pipefail
cd "$(dirname "$0")/../.."
source core/adapters/build.sh

W="$WORK_ROOT"
echo "--- 1. MMSBench-Net"
rm -rf "$W/coms/metalevel-discovered" "$W/coms/meta-results-1.0-discovered" "$W/coms/temp-discovered"
python experiments/run/discover_scopes.py "$W/coms/metalevel-before-union" --rho=1.0 \
  --json="$W/coms/discovered-unions.json" --out="$W/coms/discovered-unions.txt" \
  --materialize="$W/coms/metalevel-discovered" > /dev/null
java -Xmx8g -cp "$MM_CP" SpindMetaLevel "$(mm_path "$W/coms/metalevel-discovered")" 1.0 \
  "$(mm_path "$W/coms/temp-discovered")" "$(mm_path "$W/coms/meta-results-1.0-discovered")" \
  > "$W/coms/ind-1.0-discovered.log" 2>&1
echo "--- 1b. LDBC SNB (second natural instance; build_ldbc.py converts the CsvBasic dump)"
python experiments/datasets/build_ldbc.py
rm -rf "$W/ldbc/metalevel-discovered" "$W/ldbc/meta-results-1.0" "$W/ldbc/meta-results-1.0-discovered"
java -Xmx8g -cp "$MM_CP" SpindMetaLevel "$(mm_path "$W/ldbc/metalevel")" 1.0 \
  "$(mm_path "$W/ldbc/temp")" "$(mm_path "$W/ldbc/meta-results-1.0")" > "$W/ldbc/ind-1.0.log" 2>&1
python experiments/run/discover_scopes.py "$W/ldbc/metalevel" --rho=1.0 \
  --json="$W/ldbc/discovered-unions.json" --out="$W/ldbc/discovered-unions.txt" \
  --materialize="$W/ldbc/metalevel-discovered" > /dev/null
python experiments/run/propose_unions.py "$W/ldbc/metalevel" --out="$W/ldbc/shape-unions.txt" > /dev/null
java -Xmx8g -cp "$MM_CP" SpindMetaLevel "$(mm_path "$W/ldbc/metalevel-discovered")" 1.0 \
  "$(mm_path "$W/ldbc/temp")" "$(mm_path "$W/ldbc/meta-results-1.0-discovered")" \
  > "$W/ldbc/ind-1.0-discovered.log" 2>&1
python experiments/report/scope_discovery.py
grep -E '^proposed' "$W/ldbc/shape-unions.txt" | sed 's/^/  LDBC shape rule: /'

echo "--- 2. stress test"
python experiments/run/scope_discovery_stress.py --out=paper/tables/scope-discovery-stress.txt

echo "--- 3. negative control"
{
  echo "# Union discovery on instances that document no union (rho = 1, u = 0.5)."
  echo "# Generated by experiments/run/scope_discovery_all.sh."
  for i in mm_tpch unibench imdb musicbrainz movielens hpatent hperson hfilm huniversity listenbrainz; do
    [ -f "$W/$i/metalevel/catalog.json" ] || { echo "  $i: no export"; continue; }
    python experiments/run/discover_scopes.py "$W/$i/metalevel" --out="$W/$i/discovered-unions.txt" > /dev/null
    printf '  %-13s %s\n' "$i" "$(grep -E '^(dimensions|unions|time)' "$W/$i/discovered-unions.txt" | tr -s ' ' | tr '\n' ';')"
    sed -n '/^discovered/,$p' "$W/$i/discovered-unions.txt" | sed 's/^/      /'
  done
} | tee paper/tables/scope-discovery-negative.txt

echo "--- 4. split benchmark"
python experiments/run/scope_discovery_benchmark.py
